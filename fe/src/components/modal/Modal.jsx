import { useEffect, useRef, useId } from "react";
import { X } from "lucide-react";
import "./modal.css";

const FOCUSABLE_SELECTOR =
  'button:not([disabled]), [href], input:not([disabled]), select:not([disabled]), textarea:not([disabled]), [tabindex]:not([tabindex="-1"])';

// Global tracker for the last active element outside any modal
let lastActiveElementOutsideModal = null;
if (typeof document !== "undefined") {
  document.addEventListener(
    "focusin",
    (e) => {
      if (!e.target.closest || !e.target.closest('[role="dialog"], .modal-backdrop')) {
        lastActiveElementOutsideModal = e.target;
      }
    },
    true
  );
}

export default function Modal({
  isOpen,
  onClose,
  title,
  children,
  className = "",
  showCloseButton = true,
  ariaDescribedBy,
  triggerElement,
}) {
  const dialogRef = useRef(null);
  const backdropRef = useRef(null);
  const triggerElementRef = useRef(null);
  const autoGeneratedTitleId = useId();
  const titleId = `modal-title-${autoGeneratedTitleId.replace(/:/g, "")}`;

  const restoreFocus = () => {
    const target = triggerElementRef.current;
    if (target && typeof target.focus === "function" && document.body.contains(target)) {
      try {
        target.focus();
      } catch (err) {
        // ignore
      }
    }
  };

  // Save triggering element and manage focus
  useEffect(() => {
    if (!isOpen) return;

    // Capture element that had focus before modal opened
    const active = document.activeElement;
    const isInsideDialog = dialogRef.current && dialogRef.current.contains(active);
    triggerElementRef.current =
      triggerElement ||
      (!isInsideDialog && active && active !== document.body ? active : null) ||
      lastActiveElementOutsideModal;

    // Shift focus into modal
    const timer = setTimeout(() => {
      if (!dialogRef.current) return;
      const focusable = dialogRef.current.querySelectorAll(FOCUSABLE_SELECTOR);
      // Look for an autofocus element first
      const autoFocusEl = dialogRef.current.querySelector("[autofocus]");
      if (autoFocusEl) {
        autoFocusEl.focus();
      } else if (focusable.length > 0) {
        focusable[0].focus();
      } else {
        dialogRef.current.focus();
      }
    }, 10);

    // Prevent body scrolling while modal is open
    const originalOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";

    return () => {
      clearTimeout(timer);
      document.body.style.overflow = originalOverflow;
      restoreFocus();
    };
  }, [isOpen, triggerElement]);

  // Handle keyboard trap and Escape key
  const handleKeyDown = (e) => {
    if (e.key === "Escape") {
      e.preventDefault();
      e.stopPropagation();
      restoreFocus();
      onClose();
      return;
    }

    if (e.key === "Tab") {
      if (!dialogRef.current) return;
      const focusable = Array.from(
        dialogRef.current.querySelectorAll(FOCUSABLE_SELECTOR)
      ).filter((el) => el.offsetParent !== null); // visible elements

      if (focusable.length === 0) {
        e.preventDefault();
        return;
      }

      const firstEl = focusable[0];
      const lastEl = focusable[focusable.length - 1];

      if (e.shiftKey) {
        if (document.activeElement === firstEl || !dialogRef.current.contains(document.activeElement)) {
          e.preventDefault();
          lastEl.focus();
        }
      } else {
        if (document.activeElement === lastEl || !dialogRef.current.contains(document.activeElement)) {
          e.preventDefault();
          firstEl.focus();
        }
      }
    }
  };

  // Click outside backdrop cancels dialog without triggering destructive actions
  const handleBackdropClick = (e) => {
    if (e.target === backdropRef.current) {
      restoreFocus();
      onClose();
    }
  };

  if (!isOpen) return null;

  return (
    <div
      ref={backdropRef}
      className="modal-backdrop"
      onClick={handleBackdropClick}
      onKeyDown={handleKeyDown}
    >
      <div
        ref={dialogRef}
        role="dialog"
        aria-modal="true"
        aria-labelledby={title ? titleId : undefined}
        aria-describedby={ariaDescribedBy}
        tabIndex={-1}
        className={`modal-dialog ${className}`.trim()}
      >
        <div className="modal-header">
          {title && (
            <h2 id={titleId} className="modal-title">
              {title}
            </h2>
          )}
          {showCloseButton && (
            <button
              type="button"
              className="modal-close-btn"
              onClick={() => {
                restoreFocus();
                onClose();
              }}
              aria-label="Close dialog"
            >
              <X size={15} />
            </button>
          )}
        </div>
        {children}
      </div>
    </div>
  );
}
